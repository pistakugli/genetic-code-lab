#!/usr/bin/env ts-node

/**
 * Write the state of a delegated citation into the artifact that makes it.
 *
 * 210 citations in `nn-live-blind-swiglu-layer-expansion` point at a shared sweep report
 * that a later run has since overwritten. The published numbers were real when they were
 * copied, but nothing on disk can prove that any more: those artifacts predate
 * `sweepReportSha256`, so the bytes they read are gone. Six of them publish `pass: true`
 * against a witness that now reads `fail`.
 *
 * Until now that was visible only to `verify-delegated-citations.ts`. A reader opening one
 * of these reports saw a citation to a path, and a path that exists reads as evidence. This
 * writes the truth into the artifact itself: which fields diverged, what the target says
 * today, and that the citation cannot be verified because it carries no digest.
 *
 * What this deliberately does not do:
 *
 *   - it does not touch any measured number, verdict, or manifest status
 *   - it does not remove a citation, because a stale citation is a fact worth keeping
 *   - it does not make anything stop counting as broken; the baseline ratchet in the
 *     verifier is untouched, and the labelled citations still fail an unlabelled check
 *
 * Only a rerun can restore provable evidence. None of these 207 artifacts is referenced by
 * any document or regenerated by `release-gate.ts`, so the honest resolution for them is an
 * accurate label rather than 70 GPU hours spent re-earning numbers nothing cites.
 *
 * Idempotent: re-running refreshes the record rather than appending a second one.
 * `--check` reports what would change and writes nothing.
 */

import fs from 'fs';
import path from 'path';

const repoRoot = path.resolve(__dirname, '..');
const releaseRoot = path.join(repoRoot, 'benchmarks', 'release');
const checkOnly = process.argv.includes('--check');

/** The same fields verify-delegated-citations.ts compares, kept in step with it. */
const COMPARED_FIELDS = [
  'pass',
  'caseCount',
  'passedCases',
  'failedCases',
  'minR2',
  'maxMae',
  'maxWorstError',
  'minSubspacePrincipalCosine',
  'minPairedAtomJointCosine',
  'maxRawOracleCallsPerCase',
  'totalRawOracleCalls',
  'accessInvariant'
] as const;

export const CITATION_EVIDENCE_KEY = 'citationEvidence';
export const UNVERIFIABLE_STATE = 'unverifiable-legacy-citation';

type CitationEvidence = {
  state: typeof UNVERIFIABLE_STATE;
  reason: string;
  divergedFields: string[];
  publishedVsCurrent: Record<string, { published: unknown; current: unknown }>;
  targetPassNow: unknown;
  repair: string;
};

function readJson(filePath: string): Record<string, unknown> | null {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8')) as Record<string, unknown>;
  } catch {
    return null;
  }
}

function walkReports(dir: string, found: string[] = []): string[] {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkReports(full, found);
    else if (entry.name === 'report.json') found.push(full);
  }
  return found;
}

export function divergedFields(
  published: Record<string, unknown> | undefined,
  current: Record<string, unknown> | undefined
): string[] {
  const a = published ?? {};
  const b = current ?? {};
  return COMPARED_FIELDS.filter(
    field => (field in a || field in b) && JSON.stringify(a[field]) !== JSON.stringify(b[field])
  );
}

export function buildEvidence(
  published: Record<string, unknown> | undefined,
  current: Record<string, unknown> | undefined,
  fields: string[]
): CitationEvidence {
  const publishedVsCurrent: Record<string, { published: unknown; current: unknown }> = {};
  for (const field of fields) {
    publishedVsCurrent[field] = { published: (published ?? {})[field], current: (current ?? {})[field] };
  }
  const publishedPass = (published ?? {}).pass;
  const currentPass = (current ?? {}).pass;
  const passReversed = publishedPass === true && currentPass === false;
  return {
    state: UNVERIFIABLE_STATE,
    reason:
      'This citation names a shared, mutable sweep report and predates sweepReportSha256, so the bytes ' +
      'it published cannot be re-read. The target has since been overwritten and no longer matches.' +
      (passReversed
        ? ' The published summary says pass while the target now reads fail, so this artifact\'s own ' +
          'verdict rests on a witness that no longer supports it.'
        : ''),
    divergedFields: fields,
    publishedVsCurrent,
    targetPassNow: currentPass,
    repair:
      'Rerun the lane to produce a self-contained, digest-pinned citation. Nothing short of a rerun ' +
      'can restore provable evidence for the numbers above.'
  };
}

let artifactsChanged = 0;
let citationsLabelled = 0;
let alreadyLabelled = 0;
let passReversedCount = 0;

for (const reportPath of walkReports(releaseRoot)) {
  const report = readJson(reportPath);
  if (!report) continue;
  const cases = Array.isArray(report.cases) ? report.cases : [];
  if (!cases.length) continue;

  let changed = false;
  for (const entry of cases) {
    if (!entry || typeof entry !== 'object') continue;
    const record = entry as Record<string, unknown>;
    const target = record.sweepReportPath;
    if (typeof target !== 'string' || !target) continue;
    // A digest-pinned citation proves itself; only the unpinned legacy ones need a label.
    if (typeof record.sweepReportSha256 === 'string') continue;

    const targetReport = readJson(path.join(repoRoot, target));
    const published = record.sweepSummary as Record<string, unknown> | undefined;
    const current = targetReport?.summary as Record<string, unknown> | undefined;
    const fields = divergedFields(published, current);
    if (!fields.length) continue;

    const evidence = buildEvidence(published, current, fields);
    if (evidence.reason.includes('pass while the target now reads fail')) passReversedCount++;
    const existing = record[CITATION_EVIDENCE_KEY];
    if (JSON.stringify(existing) === JSON.stringify(evidence)) {
      alreadyLabelled++;
      continue;
    }
    record[CITATION_EVIDENCE_KEY] = evidence;
    citationsLabelled++;
    changed = true;
  }

  if (!changed) continue;
  artifactsChanged++;
  if (!checkOnly) fs.writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);

  // The markdown is what a person actually reads, so the warning has to reach it too.
  const markdownPath = path.join(path.dirname(reportPath), 'report.md');
  if (!fs.existsSync(markdownPath)) continue;
  const marker = '> Citation warning:';
  const lines = fs.readFileSync(markdownPath, 'utf8').split('\n').filter(line => !line.startsWith(marker));
  const warning =
    `${marker} this report's delegated citation(s) point at a shared sweep report that has since been ` +
    'overwritten, and predate digest pinning, so the numbers below cannot be verified against their source. ' +
    'See citationEvidence in report.json.';
  const insertAt = lines.findIndex(line => line.trim() === '') + 1;
  lines.splice(insertAt > 0 ? insertAt : lines.length, 0, warning, '');
  if (!checkOnly) fs.writeFileSync(markdownPath, lines.join('\n'));
}

console.log(
  JSON.stringify(
    {
      mode: checkOnly ? 'check' : 'write',
      artifactsChanged,
      citationsLabelled,
      alreadyLabelled,
      passReversedCitations: passReversedCount
    },
    null,
    2
  )
);

if (checkOnly && citationsLabelled) {
  console.error(`\n${citationsLabelled} unverifiable citation(s) are not labelled. Run without --check to write the record.`);
  process.exit(1);
}
